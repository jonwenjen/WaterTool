/** 取得方法參數的說明（深度模型共用 net.*） */
export function paramHelp(method, key) {
  return HELP[`${method.id}.${key}`] || (method.needsModel ? HELP[`net.${key}`] : null);
}

/** 說明的 HTML（<details>，預設收起） */
export function helpHtml(h) {
  if (!h) return '';
  return `<details class="help"><summary>說明</summary><dl>
    <dt>往小</dt><dd>${h.low}</dd><dt>往大</dt><dd>${h.high}</dd>
    <dt>適用</dt><dd>${h.use}</dd><dt>建議</dt><dd>${h.rec}</dd></dl></details>`;
}
