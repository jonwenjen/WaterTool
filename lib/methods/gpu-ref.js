// GPU（WebGPU）結果自我檢查：每個深度模型在一張固定的測試畫面上的網路輸出「指紋」（CPU／WASM 算的）。
// worker.js 用 WebGPU 載入模型後先跑這張畫面，指紋對不上（少數裝置／驅動的 WebGPU 會算錯，而且數值看起來正常、
// 不是 NaN）就把這個模型改用 CPU。指紋由 scripts/gpu-ref.mjs 產生；模型檔或輸入格式改變時要重新產生。
import * as C from '../core.js';
import { netSize } from './net.js';

/** 固定的測試畫面（320×180，帶顏色漸層與紋理，像偏藍綠的水下畫面） */
export function testImage() {
  const w = 320, h = 180, img = C.create(w, h);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const i = y * w + x, t = Math.sin(x * 0.11) * Math.cos(y * 0.07);
    img.c[0][i] = 0.08 + 0.25 * (x / w) + 0.05 * t;
    img.c[1][i] = 0.35 + 0.3 * (y / h) + 0.08 * t;
    img.c[2][i] = 0.4 + 0.2 * ((x + y) / (w + h)) - 0.06 * t;
  }
  return img;
}

/** 方法 → 網路輸入（與 net.js 的 estimate 相同的縮放與換算）{ x, w, h } */
export function testInput(spec) {
  const img = testImage(), [nw, nh] = netSize(img.w, img.h, spec), small = C.resize(img, nw, nh), n = nw * nh;
  if (spec.buildInput) return { x: spec.buildInput(small), w: nw, h: nh };
  const x = new Float32Array(3 * n), f = spec.input === 'pm1' ? (v) => v * 2 - 1 : (v) => v;
  for (let c = 0; c < 3; c++) for (let i = 0; i < n; i++) x[c * n + i] = f(small.c[c][i]);
  return { x, w: nw, h: nh };
}

/** 網路輸出（CHW）→ 指紋：前 3 個通道各分成 4×4 格的平均（48 個數） */
export function fingerprint(y, w, h) {
  const n = w * h, out = [];
  for (let c = 0; c < 3; c++) for (let gy = 0; gy < 4; gy++) for (let gx = 0; gx < 4; gx++) {
    let s = 0, k = 0;
    for (let yy = Math.floor((gy * h) / 4); yy < Math.floor(((gy + 1) * h) / 4); yy++) {
      for (let xx = Math.floor((gx * w) / 4); xx < Math.floor(((gx + 1) * w) / 4); xx++) { s += y[c * n + yy * w + xx]; k++; }
    }
    out.push(+(s / k).toFixed(4));
  }
  return out;
}

/** 兩個指紋相差多少（相對於輸出範圍） */
export function fingerprintDiff(a, b) {
  const range = Math.max(1e-6, Math.max(...b) - Math.min(...b));
  let worst = 0;
  for (let i = 0; i < b.length; i++) worst = Math.max(worst, Math.abs(a[i] - b[i]));
  return worst / range;
}

